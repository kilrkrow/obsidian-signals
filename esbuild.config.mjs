import esbuild from "esbuild";
import { copyFileSync, mkdirSync } from "node:fs";
import { builtinModules } from "node:module";
import { join } from "node:path";
import process from "node:process";

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: {
    js: "/* Generated by esbuild. Source is src/. */",
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: ["obsidian", "electron", ...builtinModules, ...builtinModules.map((name) => `node:${name}`)],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: false,
  treeShaking: true,
  outfile: "main.js",
  plugins: [
    {
      name: "install-into-vault",
      setup(build) {
        build.onEnd((result) => {
          if (result.errors.length) return;
          const devVault = process.env.SIGNALS_DEV_VAULT;
          if (!devVault) return;
          const dest = join(devVault, ".obsidian", "plugins", "signals");
          mkdirSync(dest, { recursive: true });
          for (const file of ["main.js", "manifest.json", "styles.css"]) {
            copyFileSync(file, join(dest, file));
          }
          console.log("installed", dest);
        });
      },
    },
  ],
});

await context.rebuild();
if (prod) process.exit(0);
await context.watch();
